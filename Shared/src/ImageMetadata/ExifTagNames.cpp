std::string_view exifTagName(ExifDirectory directory, uint16_t tag) noexcept
{
	using Names = std::span<const TagName>;
	const Names names = directory == ExifDirectory::Gps ? Names{ GpsTags }
		: directory == ExifDirectory::Interoperability  ? Names{ InteroperabilityTags }
		                                                : Names{ TiffTags };
	const auto found = std::ranges::lower_bound(names, tag, {}, &TagName::tag);
	return found != names.end() && found->tag == tag ? found->name : std::string_view{};
}

